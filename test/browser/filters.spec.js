const { test, expect } = require('@playwright/test');

test('account filters persist through modes, dates, reloads and a new browser session, with scoped defaults', async ({ page, browser }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const login = async target => {
    await target.goto('/session/new');
    await target.getByLabel('Email', { exact: true }).fill(process.env.TEST_EMAIL || 'demo@example.test');
    await target.getByLabel('Password', { exact: true }).fill(process.env.TEST_PASSWORD || 'synthetic-pass-123');
    await target.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(target.getByRole('heading', { name: 'Your health, over time.' })).toBeVisible();
  };
  const saved = async () => expect(page.locator('[data-chart-preferences-target="status"]')).toHaveText('Selections saved.');
  const dialog = page.getByRole('dialog');
  await login(page);
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await expect(page.getByRole('menu', { name: 'Appearance', exact: true })).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('menuitemradio', { name: 'Light', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('html')).toHaveAttribute('data-theme-preference', 'light');
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.getByRole('menuitemradio', { name: 'Dark', exact: true }).click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme-preference', 'dark');
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await expect(page.getByRole('menuitemradio', { name: 'Dark', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.screenshot({ path: `test/artifacts/${testInfo.project.name}-appearance-icon-menu.png`, fullPage: true });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Appearance', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.getByRole('menuitemradio', { name: 'System', exact: true }).click();
  await page.goto('/injections');
  await expect(page.locator('section[aria-labelledby="trajectory-heading"]').getByRole('button', { name: 'Filter injections', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Filter injections', exact: true }).click();
  await expect(page.getByLabel('Date range', { exact: true })).toBeFocused();
  await page.getByLabel('From (custom)', { exact: true }).fill('2026-11-09');
  await page.getByLabel('Through (custom)', { exact: true }).fill('2026-11-15');
  await expect(page.getByLabel('Date range', { exact: true })).toHaveValue('custom');
  await page.getByLabel('Location', { exact: true }).selectOption('Thigh');
  await page.getByLabel('Side', { exact: true }).selectOption('Left');
  await page.getByLabel('Dose', { exact: true }).selectOption('5.0');
  await page.getByLabel('Compare locations by', { exact: true }).selectOption('site');
  await page.screenshot({ path: `test/artifacts/${testInfo.project.name}-injection-filter-modal.png`, fullPage: true });
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('.active-filter-summary')).toContainText('Thigh');
  for (const mode of ['aligned', 'calendar', 'aligned']) {
    await page.getByRole('combobox', { name: 'Chart view', exact: true }).selectOption(mode);
  }
  await saved();
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Chart view', exact: true })).toHaveValue('aligned');
  await page.getByRole('button', { name: 'Filter injections', exact: true }).click();
  await expect(page.getByLabel('Location', { exact: true })).toHaveValue('Thigh');
  await expect(page.getByLabel('Side', { exact: true })).toHaveValue('Left');
  await expect(page.getByLabel('Dose', { exact: true })).toHaveValue('5.0');
  await expect(page.getByLabel('Compare locations by', { exact: true })).toHaveValue('site');
  await page.getByLabel('Location', { exact: true }).selectOption('Abdomen');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Filter injections', exact: true }).click();
  await expect(page.getByLabel('Location', { exact: true })).toHaveValue('Thigh');
  await page.getByLabel('Date range', { exact: true }).selectOption('30');
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Chart view', exact: true })).toHaveValue('aligned');
  await expect(page.locator('.compact-injection-summary')).not.toContainText('MEAN COMPLETED-WINDOW');
  await expect(page.locator('.compact-injection-stat')).toHaveCount(2);
  const cardWidths = await page.locator('.compact-injection-stat').evaluateAll(cards => cards.map(card => card.getBoundingClientRect().width));
  expect(Math.abs(cardWidths[0] - cardWidths[1])).toBeLessThan(1);
  await page.goto('/');
  await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('weekly');
  await saved();
  await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('monthly');
  await saved();
  await page.getByRole('button', { name: 'Filter overview chart', exact: true }).click();
  await page.getByLabel('Date range', { exact: true }).selectOption('7');
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('monthly');
  await page.getByLabel('7-day trend', { exact: true }).uncheck();
  await saved();
  await page.getByLabel('7-day trend', { exact: true }).check();
  await saved();
  await page.getByRole('button', { name: 'Filter overview chart', exact: true }).click();
  await page.getByLabel('From (custom)', { exact: true }).fill('2026-11-09');
  await page.getByLabel('Through (custom)', { exact: true }).fill('2026-11-15');
  await page.screenshot({ path: `test/artifacts/${testInfo.project.name}-overview-filter-modal.png`, fullPage: true });
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('monthly');
  await expect(page.getByLabel('7-day trend', { exact: true })).toBeChecked();
  const otherContext = await browser.newContext({ baseURL: process.env.BASE_URL || 'http://127.0.0.1:3100' });
  try {
    const second = await otherContext.newPage();
    await login(second);
    await expect(second.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('monthly');
    await expect(second.getByLabel('7-day trend', { exact: true })).toBeChecked();
    await second.goto('/injections');
    await expect(second.getByRole('combobox', { name: 'Chart view', exact: true })).toHaveValue('aligned');
    await expect(second.locator('.active-filter-summary')).toContainText('Thigh');
  } finally { await otherContext.close(); }
  await page.getByRole('button', { name: 'Filter overview chart', exact: true }).click();
  await page.getByRole('button', { name: 'Clear / defaults', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('raw');
  await expect(page.getByLabel('7-day trend', { exact: true })).not.toBeChecked();
  await expect(page.getByRole('button', { name: 'Filter overview chart', exact: true })).toContainText('30 days');
  await page.goto('/injections');
  await expect(page.getByRole('combobox', { name: 'Chart view', exact: true })).toHaveValue('aligned');
  await expect(page.locator('.active-filter-summary')).toContainText('Thigh');
  await page.getByRole('button', { name: 'Filter injections', exact: true }).click();
  await page.getByRole('button', { name: 'Clear / defaults', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Chart view', exact: true })).toHaveValue('calendar');
  await expect(page.getByRole('button', { name: 'Filter injections', exact: true })).toContainText('90 days');
  const gradient = await page.locator('[data-injection-insights-target="trajectory"]').evaluate(canvas => {
    const chart = Chart.getChart(canvas);
    return { fill: chart.data.datasets[0].fill, gradient: chart.getDatasetMeta(0).dataset.options.backgroundColor instanceof CanvasGradient };
  });
  expect(gradient).toEqual({ fill: 'start', gradient: true });
  await page.locator('.compact-injection-summary').screenshot({ path: `test/artifacts/${testInfo.project.name}-compact-injection-summary.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
